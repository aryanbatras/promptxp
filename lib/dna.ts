import type { CurationMap, Prompt } from "./types";

interface StackSignal {
  name: string;
  pattern: RegExp;
}

const STACK: StackSignal[] = [
  { name: "Next.js", pattern: /\bnext\.?js\b/i },
  { name: "React", pattern: /\breact\b/i },
  { name: "TypeScript", pattern: /\btypescript\b|\bts\b/i },
  { name: "Tailwind CSS", pattern: /\btailwind\b/i },
  { name: "shadcn/ui", pattern: /\bshadcn\b/i },
  { name: "Astro", pattern: /\bastro\b/i },
  { name: "Node.js", pattern: /\bnode(?:\.js)?\b/i },
  { name: "Python", pattern: /\bpython\b/i },
  { name: "Java / Spring", pattern: /\bspring\s*boot\b|\bjava\b/i },
  { name: "PostgreSQL", pattern: /\bpostgres(?:ql)?\b/i },
  { name: "SQLite", pattern: /\bsqlite\b/i },
  { name: "Docker", pattern: /\bdocker\b/i },
  { name: "AWS", pattern: /\baws\b|\bec2\b|\bs3\b/i },
  { name: "Vercel", pattern: /\bvercel\b/i },
  { name: "Cloudflare", pattern: /\bcloudflare\b|\bworkers\b/i },
  { name: "Playwright", pattern: /\bplaywright\b/i },
  { name: "MCP", pattern: /\bmcp\b/i },
  { name: "Flutter", pattern: /\bflutter\b/i },
  { name: "Supabase", pattern: /\bsupabase\b/i },
  { name: "Prisma / Drizzle", pattern: /\bprisma\b|\bdrizzle\b/i },
];

const RULE_LINE =
  /^\s*(?:[-*•]\s+|\d+[.)]\s+)?(?:use|never|always|do not|don't|must|avoid|prefer|no|only|keep|ensure|require)\b/i;

export interface DnaProfile {
  generatedAt: number;
  sampleSize: number;
  curatedSize: number;
  kinds: Array<{ kind: string; count: number }>;
  stack: Array<{ name: string; count: number }>;
  rules: Array<{ text: string; project: string; promptId: string }>;
  tags: Array<{ tag: string; count: number }>;
  projects: Array<{ name: string; count: number }>;
  markdown: string;
}

export function buildDna(
  prompts: Prompt[],
  curation: CurationMap,
  limit = 150,
): DnaProfile {
  const withCuration = prompts
    .filter((prompt) => !curation[prompt.id]?.hidden)
    .map((prompt) => ({ prompt, curation: curation[prompt.id] ?? {} }));

  const curated = withCuration.filter(
    (entry) => entry.curation.starred || (entry.curation.tags?.length ?? 0) > 0,
  );

  const pool = (curated.length >= 8 ? curated : withCuration)
    .filter((entry) => entry.prompt.signal)
    .sort(
      (a, b) =>
        Number(Boolean(b.curation.starred)) - Number(Boolean(a.curation.starred)) ||
        b.prompt.quality - a.prompt.quality ||
        b.prompt.createdAt - a.prompt.createdAt,
    )
    .slice(0, limit);

  const kindCounts = new Map<string, number>();
  const stackCounts = new Map<string, number>();
  const tagCounts = new Map<string, number>();
  const projectCounts = new Map<string, number>();
  const rules: DnaProfile["rules"] = [];
  const seenRules = new Set<string>();

  for (const { prompt, curation: overlay } of pool) {
    kindCounts.set(prompt.kind, (kindCounts.get(prompt.kind) ?? 0) + 1);
    projectCounts.set(prompt.projectName, (projectCounts.get(prompt.projectName) ?? 0) + 1);
    for (const tag of overlay.tags ?? []) tagCounts.set(tag, (tagCounts.get(tag) ?? 0) + 1);
    for (const signal of STACK) {
      if (signal.pattern.test(prompt.text)) {
        stackCounts.set(signal.name, (stackCounts.get(signal.name) ?? 0) + 1);
      }
    }
    for (const line of prompt.text.split("\n")) {
      if (line.length < 18 || line.length > 240) continue;
      if (!RULE_LINE.test(line)) continue;
      const text = line
        .replace(/^\s*(?:[-*•]\s+|\d+[.)]\s+)/, "")
        .replace(/[\w.+-]+@[\w-]+\.[\w.]+/g, "{{email}}")
        .replace(/\+?\d[\d\s()-]{7,}\d/g, "{{phone}}")
        .trim();
      const key = text.toLowerCase().replace(/\s+/g, " ");
      if (seenRules.has(key)) continue;
      seenRules.add(key);
      rules.push({ text, project: prompt.projectName, promptId: prompt.id });
      if (rules.length >= 60) break;
    }
  }

  const stack = Array.from(stackCounts.entries())
    .map(([name, count]) => ({ name, count }))
    .sort((a, b) => b.count - a.count)
    .slice(0, 12);
  const kinds = Array.from(kindCounts.entries())
    .map(([kind, count]) => ({ kind, count }))
    .sort((a, b) => b.count - a.count);
  const tags = Array.from(tagCounts.entries())
    .map(([tag, count]) => ({ tag, count }))
    .sort((a, b) => b.count - a.count);
  const projects = Array.from(projectCounts.entries())
    .map(([name, count]) => ({ name, count }))
    .sort((a, b) => b.count - a.count);

  const topRules = rules.slice(0, 30);

  const markdown = [
    "# Engineering DNA",
    "",
    `Derived from ${pool.length} of your highest-signal prompts${curated.length >= 8 ? " (starred and tagged first)" : ""}.`,
    "These are your own words and defaults, aggregated locally. Nothing was generated by a model.",
    "",
    "## Default stack",
    stack.length
      ? stack.map((entry) => `- ${entry.name} — referenced in ${entry.count} prompts`).join("\n")
      : "- No stack signals yet. Star a few prompts so this becomes meaningful.",
    "",
    "## Standing rules",
    topRules.length
      ? topRules.map((rule) => `- ${rule.text}`).join("\n")
      : "- No explicit rules captured yet. Prompts with “use / never / always” lines surface here.",
    "",
    "## Working modes",
    kinds.length
      ? kinds.map((entry) => `- ${entry.kind}: ${entry.count} prompts`).join("\n")
      : "- —",
    "",
    "## Recently active projects",
    projects.length
      ? projects.slice(0, 8).map((entry) => `- ${entry.name} (${entry.count})`).join("\n")
      : "- —",
  ].join("\n");

  return {
    generatedAt: Date.now(),
    sampleSize: pool.length,
    curatedSize: curated.length,
    kinds,
    stack,
    rules: topRules,
    tags,
    projects: projects.slice(0, 10),
    markdown,
  };
}
